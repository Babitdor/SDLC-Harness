"""Project workspace management — wiki-style sandbox layout, DAG, and lineage.

Every project gets an isolated directory inside the Docker container, organised
by SDLC phase instead of the older flat ``artifacts/`` dump:

    /workspace/project_<id>/
    ├── index.md             # Auto-regenerated entry point
    ├── log.md               # System-written change history
    ├── sources/             # Raw user-supplied files + extracted markdown
    ├── requirements/        # REQUIREMENTS.md, GLOSSARY.md, CONSTRAINTS.md,
    │                        # USER_STORIES.md, ACCEPTANCE_CRITERIA.md
    ├── design/              # ARCHITECTURE.md, DATA_MODEL.md, ADR.md,
    │                        # API_SPEC.md, openapi.yaml
    ├── planning/            # BACKLOG.md, TEST_PLAN.md, CI_CD.md, ci/pipeline.yml
    ├── diagrams/            # sequence/class/state/erd/deployment .mmd
    └── metadata/            # project_graph.json, lineage.json

The phase folders correspond to five SDLC phases, with an upstream ``sources/``
bucket for user input and a ``diagrams/`` bucket for validated Mermaid models.
``index.md`` is regenerated by the artifact-listing path whenever it detects a
change (see artifacts.regenerate_index).
"""

from __future__ import annotations

import json
import logging
from datetime import datetime, timezone
from typing import Any

from sdlc.sandbox.docker_backend import DockerBackend

logger = logging.getLogger(__name__)

# Ordered list of phase folder names. Used by artifacts.py for the index
# rendering order and by FileExplorer on the frontend to render the groups.
PHASES: tuple[str, ...] = (
    "sources",
    "requirements",
    "design",
    "planning",
    "diagrams",
)

# ── Default project graph (artifact dependency DAG) ────────────────────
# Paths are phase-qualified to match the on-disk layout.

CURRENT_LINK = "/workspace/current"

