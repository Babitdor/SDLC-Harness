# ── Artifact → agent reverse mapping ────────────────────────────────────

ARTIFACT_AGENT: dict[str, str] = {}
for _agent, _arts in AGENT_ARTIFACTS.items():
    for _art in _arts:
        ARTIFACT_AGENT[_art] = _agent


# ── Project workspace ───────────────────────────────────────────────────


class ProjectWorkspace:
    """Manages the sandbox directory layout and metadata for one project."""

    def __init__(self, project_id: str, backend: DockerBackend) -> None:
        self.project_id = project_id
        self.backend = backend
        self.root = f"/workspace/project_{project_id}"

        # Phase folders — single source of truth for on-disk locations.
        self.sources_dir = f"{self.root}/sources"
        self.requirements_dir = f"{self.root}/requirements"
        self.design_dir = f"{self.root}/design"
        self.planning_dir = f"{self.root}/planning"
        self.diagrams_dir = f"{self.root}/diagrams"
        self.ci_dir = f"{self.planning_dir}/ci"
        self.metadata_dir = f"{self.root}/metadata"

    # `inputs_dir` is a deprecated alias for `sources_dir`. The file-upload
    # service and the input-listing endpoint still reference it; keep it
    # working for one release before removing.
    @property
    def inputs_dir(self) -> str:
        return self.sources_dir

    # `artifacts_dir` is kept as a property so any external code probing
    # `ws.artifacts_dir` doesn't crash — but it now points at the project
    # root because artifacts are spread across phase folders. Callers
    # building paths should use phase_dir() instead.
    @property
    def artifacts_dir(self) -> str:
        return self.root

    def phase_dir(self, phase: str) -> str:
        """Return the absolute container path for a named phase folder."""
        if phase not in PHASES:
            msg = f"Unknown phase: {phase!r}. Valid phases: {PHASES}"
            raise ValueError(msg)
        return f"{self.root}/{phase}"

    def link_current_cmd(self) -> str:
        """Command that points ``/workspace/current`` at this project.

        Agents are given one fixed path rather than the real
        ``/workspace/project_<id>``. The prompt templates are module-level
        constants rendered once at import, while ``project_id`` arrives per
        request, so interpolating it would mean re-rendering all 11
        templates per request and threading ``project_id`` through
        ``create_orchestrator`` — whose agents are cached per ``thread_id``,
        so a later request naming a different project would silently keep a
        stale baked-in path. A re-pointable symlink has neither problem, and
        it removes the ``project_*`` glob that was ambiguous whenever a
        container held more than one project.

        Invisible to the artifact inventory: ``scan_workspace_files`` walks
        ``self.root``, the real directory, so nothing is double-counted.

        ``-n`` stops a re-point from nesting the link inside itself when
        ``/workspace/current`` already resolves to a directory.
        """
        return f"ln -sfn {self.root} {CURRENT_LINK}"

    def init_directories(self) -> None:
        """Create the sandbox directory structure inside the Docker container."""
        dirs = [
            self.sources_dir,
            self.requirements_dir,
            self.design_dir,
            self.planning_dir,
            self.ci_dir,
            self.diagrams_dir,
            self.metadata_dir,
        ]
        cmd = "mkdir -p " + " ".join(dirs)
        result = self.backend.execute(cmd)
        if result.exit_code != 0:
            msg = f"Failed to create project directories: {result.output}"
            raise RuntimeError(msg)

        # Give agents the fixed path they are told to use. Best-effort: a
        # missing symlink degrades to "agent must glob", which is the old
        # behaviour, so it must never fail workspace creation.
        self.backend.execute(self.link_current_cmd())

        # Create initial OKF-compatible log.md
        # "Declared-From", not "Source": the value is the project graph's
        # declared upstream dependency, not an observation of which file
        # was actually read. Agents are told to consult this log, so the
        # header must not invite them to treat it as evidence.
        log_content = (
            "# Project Log\n\n"
            "| Date | Action | Declared-From | Target |\n"
            "|------|--------|---------------|--------|\n"
        )
        log_cmd = (
            f"cat > {self.root}/log.md << 'SDLC_LOG_EOF'\n"
            f"{log_content}"
            f"SDLC_LOG_EOF"
        )
        self.backend.execute(log_cmd)

        logger.info("Initialised project workspace at %s", self.root)

    def init_project_graph(self) -> None:
        """Write the default project_graph.json into the metadata directory."""
        self._write_json(f"{self.metadata_dir}/project_graph.json", DEFAULT_PROJECT_GRAPH)

    def write_lineage_entry(
        self,
        agent: str,
        inputs_used: list[str],
        outputs_produced: list[str],
    ) -> None:
        """Append a lineage entry to lineage.json."""
        lineage_path = f"{self.metadata_dir}/lineage.json"

        # Read existing lineage or start fresh
        lineage = self._read_json(lineage_path) or {"entries": []}

        lineage["entries"].append(
            {
                "agent": agent,
                "inputs_used": inputs_used,
                "outputs_produced": outputs_produced,
                "timestamp": datetime.now(timezone.utc).isoformat(),
            }
        )

        self._write_json(lineage_path, lineage)

    def append_log(self, action: str, source: str, target: str) -> None:
        """Append a row to the project log.md (OKF-compatible change history).

        Parameters
        ----------
        action:
            The action performed (e.g. ``"produce"``, ``"update"``, ``"ingest"``).
        source:
            The source artifact or input (e.g. ``"REQUIREMENTS.md"``).
        target:
            The target artifact produced or affected (e.g. ``"USECASES.md"``).
        """
        ts = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
        entry = f"| {ts} | {action} | {source} | {target} |\n"
        # Use single-quoted echo to avoid shell interpolation of special chars
        cmd = f"echo '{entry}' >> {self.root}/log.md"
        self.backend.execute(cmd)

    async def append_log_rows(self, rows: list[tuple[str, str, str]]) -> None:
        """Append multiple ``(action, source, target)`` rows to log.md at once.

        Bulk variant of :meth:`append_log` — used by the post-run bookkeeping
        in the chat stream so a run that changes N artifacts costs a single
        container exec rather than N. Each row shares one UTC timestamp (the
        moment the run finished). No-op when ``rows`` is empty.
        """
        if not rows:
            return
        ts = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
        body = "".join(
            f"| {ts} | {action} | {source} | {target} |\n"
            for action, source, target in rows
        )
        cmd = f"cat >> {self.root}/log.md << 'SDLC_LOG_EOF'\n{body}SDLC_LOG_EOF"
        await self.backend.execute_async(cmd)

    def get_project_graph(self) -> dict[str, Any]:
        """Read and return the project dependency graph."""
        return self._read_json(f"{self.metadata_dir}/project_graph.json") or {}

    def artifact_exists(self, artifact: str) -> bool:
        """Check whether an artifact file exists in the workspace."""
        result = self.backend.execute(f"test -f {self.root}/{artifact} && echo yes || echo no")
        return "yes" in result.output

    def resolve_dependencies(self, target_agent: str) -> list[str]:
        """Return the list of agents that must run before *target_agent*.

        Walks the project graph to find all upstream agents whose output
        artifacts are missing.
        """
        target_artifacts = AGENT_ARTIFACTS.get(target_agent, [])
        needed: list[str] = []
        visited: set[str] = set()

        def _walk(artifact: str) -> None:
            if artifact in visited:
                return
            visited.add(artifact)

            graph = self.get_project_graph()
            entry = graph.get(artifact, {})
            for dep in entry.get("depends_on", []):
                # Only process artifacts (not raw inputs)
                if dep.startswith("sources/"):
                    continue
                if not self.artifact_exists(dep):
                    agent = ARTIFACT_AGENT.get(dep, "")
                    if agent and agent not in needed:
                        needed.append(agent)
                    _walk(dep)

        for art in target_artifacts:
            if not self.artifact_exists(art):
                _walk(art)

        return needed

    # ── Private helpers ──────────────────────────────────────────────────

    def _write_json(self, path: str, data: Any) -> None:
        content = json.dumps(data, indent=2)
        # Use write_file via upload_files (BaseSandbox.write needs StateBackend)
        result = self.backend.execute(f"cat > {path} << 'DEEPAGENTS_EOF'\n{content}\nDEEPAGENTS_EOF")
        if result.exit_code != 0:
            logger.error("Failed to write %s: %s", path, result.output)

    def _read_json(self, path: str) -> Any | None:
        result = self.backend.execute(f"cat {path} 2>/dev/null")
        if result.exit_code != 0:
            return None
        try:
            return json.loads(result.output)
        except json.JSONDecodeError:
            return None
